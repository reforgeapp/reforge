package repair

import (
	"fmt"
	"strings"
	"testing"

	"github.com/reforgeapp/reforge/pkg/sandbox"
)

func TestOwnerGeneratedLicenseBatchUsesSeparateFileAndByteBounds(t *testing.T) {
	plan, baseline := testPlan(t)
	plan.Owner = true
	plan.Recipe.MaxFiles = 40
	plan.Recipe.MaxPatchBytes = 1 << 20
	plan.Recipe.MaxGenerated = 8 << 20
	plan.Digest = planDigest(plan)

	patches := make([]sandbox.Patch, 0, 181)
	for i := 0; i < 180; i++ {
		patches = append(patches, sandbox.Patch{Path: fmt.Sprintf("dist/THIRD_PARTY_LICENSES/license-%03d.txt", i), Content: []byte("third-party license\n")})
	}
	patches = append(patches, sandbox.Patch{Path: "value.js", Content: []byte("exports.add = (a,b) => a+b\n")})
	ownerErr := CheckOwnerPatch(plan, baseline, patches)
	checkpointValid := (Checkpoint{PlanDigest: plan.Digest, Patches: patches}).ValidFor(plan)
	if ownerErr != nil || !checkpointValid {
		t.Fatalf("generated license batch rejected: owner=%v checkpoint_valid=%t", ownerErr, checkpointValid)
	}

	sourceOverage := make([]sandbox.Patch, 41)
	for i := range sourceOverage {
		sourceOverage[i] = sandbox.Patch{Path: fmt.Sprintf("src/owner-%02d.js", i), Content: []byte("export default 1\n")}
	}
	sourceOwnerErr := CheckOwnerPatch(plan, baseline, sourceOverage)
	sourceCheckpointValid := (Checkpoint{PlanDigest: plan.Digest, Patches: sourceOverage}).ValidFor(plan)
	if sourceOwnerErr == nil || sourceCheckpointValid {
		t.Fatal("source file overage accepted")
	}

	generatedOverage := []sandbox.Patch{{Path: "dist/THIRD_PARTY_LICENSES/license.txt", Content: []byte(strings.Repeat("x", (8<<20)+1))}}
	generatedOwnerErr := CheckOwnerPatch(plan, baseline, generatedOverage)
	generatedCheckpointValid := (Checkpoint{PlanDigest: plan.Digest, Patches: generatedOverage}).ValidFor(plan)
	if generatedOwnerErr == nil || generatedCheckpointValid {
		t.Fatal("generated byte overage accepted")
	}
}
